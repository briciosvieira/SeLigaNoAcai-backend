import { IsOptional, IsString } from 'class-validator';

export class CreateOrderAddressDto {
  @IsOptional()
  @IsString()
  street?: string;

  @IsOptional()
  @IsString()
  number?: string;

  @IsOptional()
  @IsString()
  complement?: string;

  @IsOptional()
  @IsString()
  referencePoint?: string;
}
